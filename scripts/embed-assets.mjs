// Embeds the built SPA (./dist) into the Worker bundle as worker/assets.generated.ts,
// so a deploy is a single script upload (no separate Workers Static Assets upload).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
};

const root = new URL("../dist/", import.meta.url).pathname;
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else {
      const type = TYPES[extname(p)];
      if (!type) continue;
      files["/" + relative(root, p).split("\\").join("/")] = { type, body: readFileSync(p, "utf8") };
    }
  }
})(root);

const out = new URL("../worker/assets.generated.ts", import.meta.url).pathname;
writeFileSync(
  out,
  "// AUTO-GENERATED by scripts/embed-assets.mjs — do not edit.\n" +
    "export const ASSETS: Record<string, { type: string; body: string }> = " +
    JSON.stringify(files) +
    ";\n",
);
console.log(`embedded ${Object.keys(files).length} files into worker/assets.generated.ts`);
